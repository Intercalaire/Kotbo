const byLowercase = new Map(
  Object.entries(icons).map(([name, component]) => [name.toLowerCase(), component] as const),
);

const legacyFallbacks: Record<string, keyof typeof icons> = {
  Add: 'Plus',
  Alert: 'AlertCircle',
  ArrowRightUp: 'ArrowUpRight',
  Butterfly: 'Sparkles',
  Emoji: 'Smile',
  Font: 'Type',
  Gallery: 'Image',
  Gears: 'Settings',
  Grades: 'BarChart3',
  Paper: 'FileText',
  Pie: 'PieChart',
  Placeholder: 'Circle',
  Pronote: 'School',
  TextBubble: 'MessageCircle',
  UserCross: 'UserX',
};

export function getLucideIcon(value: unknown) {
  const requested = toPapiconsName(value);
  const fallbackName = legacyFallbacks[requested];
  if (fallbackName) return icons[fallbackName];
  return byLowercase.get(requested.toLowerCase()) ?? HelpCircle;
}
